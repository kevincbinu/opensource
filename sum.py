# Prompt user for input and convert the strings to floats to handle decimals
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

# Calculate the sum using the + operator
result = num1 + num2

# Display the final output using an f-string
print(f"The sum of {num1} and {num2} is of the value {result}")

